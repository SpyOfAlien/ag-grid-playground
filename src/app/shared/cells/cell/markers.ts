import { evaluate, type Cell, type CellRule } from './cell';
import type { TooltipContent } from '../tooltip/tooltip';

/** Highest priority first. */
export const MARKER_KINDS = [
  'error',
  'warning',
  'userEdited',
  'systemGenerated',
  'info',
  'special',
] as const;

export type MarkerKind = (typeof MARKER_KINDS)[number];

const DEFAULT_TOOLTIPS: Record<MarkerKind, string> = {
  error: 'Error',
  warning: 'Warning',
  userEdited: 'Edited by a user',
  systemGenerated: 'Generated by the system',
  info: 'Information',
  special: 'Special case',
};

export interface MarkerRule<Row, V> {
  when: CellRule<Row, V, boolean>;
  /** Defaults to the kind's own description. */
  tooltip?: CellRule<Row, V, TooltipContent>;
}

export type Markers<Row, V> = Partial<Record<MarkerKind, MarkerRule<Row, V>>>;

export interface MarkerView {
  readonly kind: MarkerKind;
  readonly tooltip: TooltipContent;
}

/** The highest-priority active marker, or null. */
export function topMarker<Row, V>(
  markers: Markers<Row, V> | undefined,
  cell: Cell<Row, V>,
): MarkerView | null {
  for (const kind of MARKER_KINDS) {
    const rule = markers?.[kind];
    if (rule && evaluate(rule.when, cell))
      return { kind, tooltip: evaluate(rule.tooltip ?? DEFAULT_TOOLTIPS[kind], cell) };
  }
  return null;
}
